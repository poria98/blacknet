async def bot_poll_loop():
    if not BOT_TOKEN:
        logger.warning("WHITE_BOT_TOKEN is not set. Bot polling will not start.")
        return

    offset = 0
    logger.info("BlackNet Telegram Bot started polling...")

    while True:
        try:
            import httpx
            async with httpx.AsyncClient(timeout=30.0) as client:
                r = await client.get(
                    f"{TG_API}/getUpdates",
                    params={"offset": offset, "timeout": 20},
                )
                if r.status_code != 200:
                    await asyncio.sleep(5)
                    continue

                for u in r.json().get("result", []):
                    offset = u["update_id"] + 1

                    if "callback_query" in u:
                        cb = u["callback_query"]
                        data = cb.get("data", "")
                        from_user = cb.get("from", {})
                        cid = from_user.get("id")
                        c_uname = from_user.get("username", "")
                        if data.startswith("buy_"):
                            await handle_buy_plan(cid, data.replace("buy_", ""), c_uname)
                        continue

                    if "message" not in u:
                        continue

                    msg = u["message"]
                    cid = msg.get("chat", {}).get("id")
                    text = msg.get("text", "") or ""
                    sender_name = msg.get("from", {}).get("first_name", "کاربر")

                    # Receipt (photo or text while waiting)
                    if "photo" in msg or USER_STEPS.get(cid, "").startswith("await_receipt_"):
                        step = USER_STEPS.get(cid, "")
                        if step.startswith("await_receipt_"):
                            order_id = step.replace("await_receipt_", "")
                            order = ORDERS.get(order_id)
                            if order:
                                USER_STEPS.pop(cid, None)
                                await activate_and_deliver(cid, order)
                        continue

                    if text == "/start":
                        await handle_start(cid, sender_name)
                    elif text == "🛍 خرید اشتراک":
                        await handle_plans(cid)
                    elif text == "📖 آموزش اتصال":
                        await handle_guide(cid)
                    elif text == "📞 پشتیبانی":
                        await send_message(
                            cid,
                            "💬 <b>پشتیبانی BlackNet</b>\n\n"
                            "https://t.me/blacknet_support\n\n"
                            "آیدی: @blacknet_support",
                        )
                    elif text == "📢 کانال رسمی":
                        await send_message(
                            cid,
                            "📢 <b>کانال رسمی BlackNet</b>\n\n"
                            "https://t.me/BlackNet_Official\n\n"
                            "برای اخبار و آپدیت‌ها عضو شوید.",
                        )

        except asyncio.CancelledError:
            break
        except Exception as e:
            logger.error(f"Error in Telegram loop: {e}")
            await asyncio.sleep(5)


if __name__ == "__main__":
    asyncio.run(bot_poll_loop())
