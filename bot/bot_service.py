class GoBackendClient:
    """HTTP client for BlackNet panel API"""

    def __init__(self, base_url: str):
        self.base_url = base_url

    async def get_plans(self) -> List[Dict[str, Any]]:
        import httpx
        try:
            async with httpx.AsyncClient(timeout=5.0) as client:
                r = await client.get(f"{self.base_url}/api/bot/sell/plans")
                if r.status_code == 200:
                    return r.json().get("plans", [])
        except Exception as e:
            logger.error(f"Failed to fetch plans: {e}")
        return [
            {"id": "plan-1", "name": "🚀 پلن برنزی (1 ماهه - 30 گیگ)", "traffic_gb": 30, "expire_days": 30, "price_toman": 85000},
            {"id": "plan-2", "name": "⚡ پلن نقره‌ای (1 ماهه - 60 گیگ)", "traffic_gb": 60, "expire_days": 30, "price_toman": 140000},
            {"id": "plan-3", "name": "💎 پلن طلایی (1 ماهه - 100 گیگ)", "traffic_gb": 100, "expire_days": 30, "price_toman": 210000},
        ]

    async def create_user_and_generate_config(
        self, username: str, traffic_gb: int, expire_days: int
    ) -> Optional[Dict[str, Any]]:
        import httpx
        payload = {
            "username": username,
            "traffic_limit": int(traffic_gb * 1024 * 1024 * 1024),
            "expire_days": int(expire_days),
            "note": f"Generated by BlackNetBot for {username}",
        }
        try:
            async with httpx.AsyncClient(timeout=10.0) as client:
                resp = await client.post(f"{self.base_url}/api/users", json=payload)
                if resp.status_code not in (200, 201):
                    logger.error(f"Create user failed: {resp.status_code} {resp.text}")
                    return None
                user_data = resp.json().get("user", {})
                cfg_uuid = user_data.get("config_uuid")
                sub_resp = await client.get(f"{self.base_url}/sub/{cfg_uuid}")
                configs = (
                    sub_resp.text.strip().split("\n") if sub_resp.status_code == 200 else []
                )
                return {
                    "user": user_data,
                    "sub_url": f"{self.base_url}/sub/{cfg_uuid}",
                    "configs": [c for c in configs if c.strip()],
                }
        except Exception as e:
            logger.error(f"create_user error: {e}")
            return None


backend_client = GoBackendClient(PANEL_API_URL)


async def tg_request(method: str, payload: Optional[Dict[str, Any]] = None) -> Optional[Dict[str, Any]]:
    if not BOT_TOKEN:
        return None
    import httpx
    try:
        async with httpx.AsyncClient(timeout=15.0) as client:
            r = await client.post(f"{TG_API}/{method}", json=payload or {})
            if r.status_code == 200:
                return r.json()
            logger.error(f"Telegram API {method}: {r.status_code} {r.text}")
    except Exception as e:
        logger.error(f"Telegram API {method}: {e}")
    return None


async def send_message(chat_id: int, text: str, reply_markup: Optional[Dict[str, Any]] = None):
    payload = {
        "chat_id": chat_id,
        "text": text,
        "parse_mode": "HTML",
        "disable_web_page_preview": True,
    }
    if reply_markup:
        payload["reply_markup"] = reply_markup
    return await tg_request("sendMessage", payload)


